using ModuleLoadFn = CUresult (*)(CUmodule*, const void*);
using GetFuncFn = CUresult (*)(CUfunction*, CUmodule, const char*);
using SetAttrFn = CUresult (*)(CUfunction, CUfunction_attribute, int);
using LaunchFn = CUresult (*)(CUfunction, unsigned, unsigned, unsigned, unsigned,
                              unsigned, unsigned, unsigned, CUstream, void**, void**);
using EncodeMapFn = CUresult (*)(CUtensorMap*, CUtensorMapDataType, cuuint32_t, void*,
                                 const cuuint64_t*, const cuuint64_t*, const cuuint32_t*,
                                 const cuuint32_t*, CUtensorMapInterleave, CUtensorMapSwizzle,
                                 CUtensorMapL2promotion, CUtensorMapFloatOOBfill);

struct CuteWsImage {
  CUfunction fn = nullptr;
  LaunchFn launch = nullptr;
  EncodeMapFn encode = nullptr;

  CuteWsImage() {
    void* h = dlopen("libcuda.so.1", RTLD_NOW | RTLD_GLOBAL);
    if (h == nullptr) {
      printf("cute_ws e3m4 gemm: cannot dlopen libcuda.so.1\n");
      return;
    }
    auto load = reinterpret_cast<ModuleLoadFn>(dlsym(h, "cuModuleLoadData"));
    auto getf = reinterpret_cast<GetFuncFn>(dlsym(h, "cuModuleGetFunction"));
    auto setattr = reinterpret_cast<SetAttrFn>(dlsym(h, "cuFuncSetAttribute"));
    launch = reinterpret_cast<LaunchFn>(dlsym(h, "cuLaunchKernel"));
    encode = reinterpret_cast<EncodeMapFn>(dlsym(h, "cuTensorMapEncodeTiled"));
    if (load == nullptr || getf == nullptr || setattr == nullptr || launch == nullptr ||
        encode == nullptr) {
      printf("cute_ws e3m4 gemm: driver entry points missing\n");
      return;
    }
    CUmodule mod = nullptr;
    if (load(&mod, kCuteWsCubin) != CUDA_SUCCESS) {
      printf("cute_ws e3m4 gemm: cuModuleLoadData failed\n");
      return;
    }
    if (getf(&fn, mod, "cute_ws") != CUDA_SUCCESS) {
      printf("cute_ws e3m4 gemm: cute_ws entry missing\n");
      fn = nullptr;
      return;
    }
    if (setattr(fn, CU_FUNC_ATTRIBUTE_MAX_DYNAMIC_SHARED_SIZE_BYTES,
                e3m4_cute_ws::SMEM_BYTES) != CUDA_SUCCESS) {
      printf("cute_ws e3m4 gemm: smem %d bytes unavailable\n", e3m4_cute_ws::SMEM_BYTES);
      fn = nullptr;
    }
  }
};

CuteWsImage& cute_ws_image() {
  static CuteWsImage img;
  return img;
}

