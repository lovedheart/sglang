struct Sm120Fp8E3m4GemmCuteWs {
  static void
  run(const tvm::ffi::TensorView out,
      const tvm::ffi::TensorView mat_a,
      const tvm::ffi::TensorView mat_b,
      const tvm::ffi::TensorView scales_a,
      const tvm::ffi::TensorView scales_b) {
    using namespace host;
    auto device = SymbolicDevice{};
    device.set_options<kDLCUDA>();
    const int M = static_cast<int>(mat_a.shape()[0]);
    const int K = static_cast<int>(mat_a.shape()[1]);
    const int N = static_cast<int>(mat_b.shape()[0]);
    TensorMatcher({M, K}).with_dtype<fp8_e4m3_t>().verify(mat_a);
    TensorMatcher({N, K}).verify(mat_b);
    TensorMatcher({M, K / 128}).with_dtype<fp32_t>().with_device(device).verify(scales_a);
    // ceil bands: a boundary tile clamps its w_scale row read to (N-1)/128,
    // so ceil(N/128) rows are in contract even when N % 128 != 0.
    TensorMatcher({(N + 127) / 128, K / 128}).with_dtype<fp32_t>().with_device(device).verify(scales_b);
    TensorMatcher({M, N}).with_dtype<bf16_t>().with_device(device).verify(out);

    host::RuntimeCheck(K % 128 == 0, "cute_ws e3m4 gemm needs K % 128 == 0, got ", K);
    host::RuntimeCheck(N % 8 == 0, "cute_ws e3m4 gemm needs N % 8 == 0, got ", N);

    auto& img = cute_ws_image();
    host::RuntimeCheck(img.fn != nullptr, "sm120_fp8_e3m4_gemm_cute_ws image unavailable");

    // Params hold two by-value CUtensorMap descriptors for A and B; the host
    // builder mirrors the device kernel's expected problem exactly (row-major
    // A [M,K], row-major B [N,K], SFA [M,K/128] and SFB [N/128,K/128] both
    // K-major — the production quantization layouts, no transposes).
    e3m4_cute_ws::Params params = e3m4_cute_ws::make_params(
        mat_a.data_ptr(), K, mat_b.data_ptr(), K,
        static_cast<float*>(scales_a.data_ptr()), static_cast<float*>(scales_b.data_ptr()),
        M, N, K);

    // C is stored through a TMA descriptor too: bf16 [M,N], 64x16 boxes,
    // 128B swizzle (the epilogue STS pack), L2-friendly promotion.
    CUtensorMap tm_c;
    const cuuint64_t gd[2] = {static_cast<cuuint64_t>(N), static_cast<cuuint64_t>(M)};
    const cuuint64_t gs[1] = {static_cast<cuuint64_t>(N) * 2};
    const cuuint32_t bx[2] = {64, 16};
    const cuuint32_t es[2] = {1, 1};
    CUresult rc = img.encode(&tm_c, CU_TENSOR_MAP_DATA_TYPE_UINT16, 2, out.data_ptr(), gd, gs,
                             bx, es, CU_TENSOR_MAP_INTERLEAVE_NONE, CU_TENSOR_MAP_SWIZZLE_128B,
                             CU_TENSOR_MAP_L2_PROMOTION_L2_128B,
                             CU_TENSOR_MAP_FLOAT_OOB_FILL_NONE);
    host::RuntimeCheck(rc == CUDA_SUCCESS, "cute_ws e3m4 gemm tensormap encode failed: ",
                       static_cast<int>(rc));

    void* d_ptr = out.data_ptr();
    int m = M, n = N, k = K;
    void* kernel_params[] = {&params, &tm_c, &d_ptr, &m, &n, &k};
    const unsigned mtiles = static_cast<unsigned>((M + 127) / 128);
    const unsigned ntiles = static_cast<unsigned>((N + 127) / 128);
    auto stream = host::LaunchKernel::resolve_device(device.unwrap());
    rc = img.launch(img.fn, mtiles * ntiles, 1, 1, e3m4_cute_ws::NUM_THREADS, 1, 1,
                    e3m4_cute_ws::SMEM_BYTES, static_cast<CUstream>(stream), kernel_params,
                    nullptr);
    host::RuntimeCheck(rc == CUDA_SUCCESS, "cute_ws e3m4 gemm cuLaunchKernel failed: ",
                       static_cast<int>(rc));
  }
};

