using ModuleLoadDataFn = CUresult (*)(CUmodule*, const void*);
using GetFuncFn = CUresult (*)(CUfunction*, CUmodule, const char*);
using SetAttrFn = CUresult (*)(CUfunction, int, int);
using LaunchFn = CUresult (*)(CUfunction, unsigned, unsigned, unsigned, unsigned,
                              unsigned, unsigned, unsigned, CUstream, void**, void**);

constexpr int kTileM = 16;
constexpr int kTileN = 32;
constexpr int kSmem = 22528;
constexpr int kMaxM = 64;

struct W6Image {
  CUfunction fn = nullptr;
  LaunchFn launch = nullptr;
};

W6Image& image() {
  static W6Image img = [] {
    W6Image out;
    void* h = dlopen("libcuda.so.1", RTLD_NOW | RTLD_GLOBAL);
    if (!h) {
      printf("sm120_fp6_e2m3_w6: cannot dlopen libcuda.so.1\n");
      return out;
    }
    auto load = reinterpret_cast<ModuleLoadDataFn>(dlsym(h, "cuModuleLoadData"));
    auto getf = reinterpret_cast<GetFuncFn>(dlsym(h, "cuModuleGetFunction"));
    auto setattr = reinterpret_cast<SetAttrFn>(dlsym(h, "cuFuncSetAttribute"));
    out.launch = reinterpret_cast<LaunchFn>(dlsym(h, "cuLaunchKernel"));
    if (!load || !getf || !setattr || !out.launch) {
      printf("sm120_fp6_e2m3_w6: driver API missing\n");
      out.launch = nullptr;
      return out;
    }
    CUmodule mod = nullptr;
    if (load(&mod, kW6Cubin) != CUDA_SUCCESS) {
      printf("sm120_fp6_e2m3_w6: cuModuleLoadData failed\n");
      return out;
    }
    if (getf(&out.fn, mod, "sm120_fp6_e2m3_gemm") != CUDA_SUCCESS) {
      printf("sm120_fp6_e2m3_w6: kernel symbol missing\n");
      out.fn = nullptr;
      return out;
    }
    if (setattr(out.fn, 8 /*MAX_DYNAMIC_SHARED*/, kSmem) != CUDA_SUCCESS) {
      printf("sm120_fp6_e2m3_w6: smem attr failed\n");
      out.fn = nullptr;
      return out;
    }
    return out;
  }();
  return img;
}

