struct Sm120Fp6E2m3W6Gemm {
  static void run(const tvm::ffi::TensorView a,
                  const tvm::ffi::TensorView b_packed,
                  const tvm::ffi::TensorView a_s,
                  const tvm::ffi::TensorView w_s,
                  const tvm::ffi::TensorView out) {
    using namespace host;
    auto device = SymbolicDevice{};
    device.set_options<kDLCUDA>();
    const int M = static_cast<int>(a.shape()[0]);
    const int K = static_cast<int>(a.shape()[1]);
    const int N = static_cast<int>(w_s.shape()[0]) * 32;
    TensorMatcher({M, K}).with_dtype<fp8_e4m3_t>().verify(a);
    TensorMatcher({static_cast<size_t>(N) * K * 6 / 8})
        .with_dtype<uint8_t>()
        .with_device(device)
        .verify(b_packed);
    TensorMatcher({M, K / 128}).with_dtype<fp32_t>().with_device(device).verify(a_s);
    TensorMatcher({N / 32, K / 32}).with_dtype<fp32_t>().with_device(device).verify(w_s);

    host::RuntimeCheck(M >= 1 && M <= kMaxM, "w6a8 band is 1..64 rows, got ", M);
    host::RuntimeCheck(K % 128 == 0, "w6a8 needs K % 128 == 0, got ", K);
    host::RuntimeCheck(N % kTileN == 0, "w6a8 needs N % 32 == 0, got ", N);

    auto& img = image();
    host::RuntimeCheck(img.fn != nullptr && img.launch != nullptr,
                       "sm120_fp6_e2m3_w6 cubin unavailable");

    void* pa = a.data_ptr();
    void* pb = b_packed.data_ptr();
    void* pc = out.data_ptr();
    void* psa = a_s.data_ptr();
    void* psw = w_s.data_ptr();
    int m = M, n = N, k = K;
    auto stream = host::LaunchKernel::resolve_device(device.unwrap());
    void* params[] = {&pa, &pb, &pc, &psa, &psw, &m, &n, &k};
    CUresult rc = img.launch(img.fn, static_cast<unsigned>((M + kTileM - 1) / kTileM),
                             static_cast<unsigned>(N / kTileN), 1, 128, 1, 1, kSmem,
                             static_cast<CUstream>(stream), params, nullptr);
    host::RuntimeCheck(rc == CUDA_SUCCESS, "sm120_fp6_e2m3_w6 cuLaunchKernel failed: ",
                       static_cast<int>(rc));
  }
};

